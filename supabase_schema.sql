-- 1. KATEGORI PRODUK
CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(100) UNIQUE NOT NULL,
    gender VARCHAR(20) DEFAULT 'all',
    icon TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. PRODUK BUSANA
-- Kolom: id, category_id, name, slug, gender, price, original_price, stock,
--        safety_stock, rack_location, sku, status, description, fabric_details,
--        care_instructions, colors, sizes, size_measurements, image_url, gallery_images,
--        rating, reviews_count, is_featured, is_new, is_sale, created_at
CREATE TABLE products (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id       BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    name              VARCHAR(255) NOT NULL,
    slug              VARCHAR(255) UNIQUE NOT NULL,
    gender            VARCHAR(20) DEFAULT 'pria',
    price             NUMERIC(12, 2) NOT NULL,
    original_price    NUMERIC(12, 2),
    stock             INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    safety_stock      INT NOT NULL DEFAULT 10,
    rack_location     VARCHAR(50) DEFAULT 'A-01-01',
    sku               VARCHAR(50) UNIQUE,
    status            VARCHAR(20) DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'discontinued')),
    description       TEXT,
    fabric_details    TEXT,
    care_instructions TEXT,
    colors            JSONB DEFAULT '[]'::jsonb,
    sizes             TEXT[] DEFAULT ARRAY['S', 'M', 'L', 'XL'],
    size_measurements JSONB DEFAULT '[]'::jsonb,
    image_url         TEXT,
    gallery_images    TEXT[] DEFAULT ARRAY[]::TEXT[],
    rating            NUMERIC(3, 2) DEFAULT 4.8,
    reviews_count     INT DEFAULT 0,
    is_featured       BOOLEAN DEFAULT FALSE,
    is_new            BOOLEAN DEFAULT FALSE,
    is_sale           BOOLEAN DEFAULT FALSE,
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. ULASAN PELANGGAN
CREATE TABLE reviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT REFERENCES products(id) ON DELETE CASCADE,
    reviewer_name  VARCHAR(100) NOT NULL,
    rating         INT CHECK (rating >= 1 AND rating <= 5),
    size_purchased VARCHAR(10),
    fit_rating     VARCHAR(50),
    comment        TEXT,
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. KUPON & VOUCHER PROMO
-- Nama kolom sinkron dengan Coupon type di lib/types.ts dan couponService.ts
-- (type, discount_amount, usage_limit, used_count, max_discount, min_purchase)
CREATE TABLE coupons (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50) UNIQUE NOT NULL,
    type            VARCHAR(20) NOT NULL CHECK (type IN ('fixed', 'percentage')),
    discount_amount NUMERIC(12, 2) NOT NULL,
    min_purchase    NUMERIC(12, 2) DEFAULT 0,
    max_discount    NUMERIC(12, 2),
    usage_limit     INT DEFAULT 100,
    used_count      INT DEFAULT 0,
    is_active       BOOLEAN DEFAULT TRUE,
    valid_until     TIMESTAMP WITH TIME ZONE,
    description     TEXT,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

