CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ------------------------------------------------------------------------------
-- 1. KATALOG
-- ------------------------------------------------------------------------------
-- category_id 1-4 dipakai hardcoded di productService.ts (filter polo/kaos/hoodie/
-- jaket/celana-panjang/celana-pendek diturunkan dari 4 kategori induk ini).
CREATE TABLE IF NOT EXISTS categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    slug       VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS products (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id       BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    name              VARCHAR(255) NOT NULL,
    slug              VARCHAR(255) NOT NULL UNIQUE,
    price             NUMERIC(12,2) NOT NULL,
    original_price    NUMERIC(12,2),
    stock             INTEGER NOT NULL DEFAULT 0,
    description       TEXT,
    fabric_details    TEXT,
    colors            JSONB DEFAULT '[]'::jsonb,
    sizes             TEXT[] DEFAULT ARRAY['S','M','L','XL'],
    image_url         TEXT,
    is_featured       BOOLEAN DEFAULT FALSE,
    is_new            BOOLEAN DEFAULT FALSE,
    created_at        TIMESTAMPTZ DEFAULT NOW(),
    gender            VARCHAR(20) DEFAULT 'unisex',
    care_instructions TEXT,
    size_measurements JSONB DEFAULT '[]'::jsonb,
    gallery_images    TEXT[] DEFAULT ARRAY[]::TEXT[],
    rating            NUMERIC(2,1) DEFAULT 4.8,
    reviews_count     INTEGER DEFAULT 0,
    sku               VARCHAR(50),
    safety_stock      INTEGER DEFAULT 10,
    rack_location     VARCHAR(50) DEFAULT 'A-01-01',
    status            VARCHAR(20) DEFAULT 'active'
);

CREATE TABLE IF NOT EXISTS reviews (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT REFERENCES products(id) ON DELETE CASCADE,
    reviewer_name VARCHAR(100) NOT NULL,
    rating        INTEGER CHECK (rating >= 1 AND rating <= 5),
    comment       TEXT,
    created_at    TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS coupons (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50) NOT NULL UNIQUE,
    type            VARCHAR(20) DEFAULT 'fixed',
    discount_amount NUMERIC(12,2) NOT NULL,
    min_purchase    NUMERIC(12,2) DEFAULT 0,
    max_discount    NUMERIC(12,2),
    usage_limit     INTEGER DEFAULT 100,
    used_count      INTEGER DEFAULT 0,
    valid_until     TIMESTAMPTZ,
    is_active       BOOLEAN DEFAULT TRUE,
    description     TEXT,
    created_at      TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 2. PENGGUNA & AUTENTIKASI
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_credentials (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email          TEXT NOT NULL UNIQUE,
    password_hash  TEXT NOT NULL,
    role           VARCHAR(50) DEFAULT 'customer',
    full_name      TEXT NOT NULL,
    phone          VARCHAR(50),
    preferred_size VARCHAR(10) DEFAULT 'M',
    created_at     TIMESTAMPTZ DEFAULT NOW(),
    updated_at     TIMESTAMPTZ DEFAULT NOW()
