-- 1. Tambah kolom katalog yang sebelumnya hanya ada di file lokal
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS out_of_stock_sizes TEXT[] DEFAULT ARRAY[]::TEXT[],
  ADD COLUMN IF NOT EXISTS is_sale BOOLEAN DEFAULT FALSE;

-- 2. Tambah kolom detail ulasan pembeli
ALTER TABLE public.reviews
  ADD COLUMN IF NOT EXISTS size_purchased VARCHAR(20) DEFAULT 'M',
  ADD COLUMN IF NOT EXISTS fit_rating VARCHAR(50) DEFAULT 'Pas Sesuai Ukuran';

-- 3. Buat ulang tabel wishlists untuk sinkronisasi tombol Love member login
CREATE TABLE IF NOT EXISTS public.wishlists (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    TEXT NOT NULL,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_wishlists_user_id ON public.wishlists (user_id);
CREATE INDEX IF NOT EXISTS idx_wishlists_product_id ON public.wishlists (product_id);

ALTER TABLE public.wishlists ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Service Role Full Wishlists" ON public.wishlists;
CREATE POLICY "Service Role Full Wishlists"
  ON public.wishlists
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);
